def d_vovk():
    rs = rows("P20_vovk_rho.csv")
    if not rs: return
    from scipy import stats as _st
    tfm = [r for r in rs if r["model"] in ORDER[:13]]
    out = ["\\begin{table}[tp]", "\\centering", "\\footnotesize",
           "\\caption{The ten efficiency criteria of Vovk et al.\\ on the main block: family means of model means, and the Spearman rank "
           "correlation of each criterion with accuracy across the 13 foundation models, with its $p$-value. Lower is better for every criterion.}",
           "\\label{tab:vovk}", "\\begin{tabular}{lcccccc}", "\\toprule", "criterion & TFM & GBDT & deep & classical & $\\rho$ within TFMs & $p$ \\\\", "\\midrule"]
    fam_of = {m: f for f in FAMORDER for m in ORDER if (m in ORDER[:13] and f == "TFM") or (m in ("catboost", "lightgbm", "xgboost") and f == "GBDT") or (m in ("tabm", "ftt", "resnet", "mlp") and f == "deep") or (m in ("LogReg", "knn") and f == "classic")}
    for c in ["S", "N", "U", "F", "M", "E", "OU", "OF", "OM", "OE"]:
        means = {}
        for f in FAMORDER:
            vals = [F(r[c]) for r in rs if fam_of.get(r["model"]) == f]
            means[f] = sum(vals) / len(vals) if vals else float("nan")
        rr = _st.spearmanr([F(r[c]) for r in tfm], [F(r["accuracy"]) for r in tfm])
        out.append(f"{c} & {f3(means['TFM'])} & {f3(means['GBDT'])} & {f3(means['deep'])} & {f3(means['classic'])} & ${rr.statistic:+.2f}$ & {pv(rr.pvalue)} \\\\")
    out += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    write("D_vovk.tex", "\n".join(out) + "\n")


