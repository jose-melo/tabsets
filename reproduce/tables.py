FAMORDER = ["TFM", "GBDT", "deep", "classic"]


def rows(name):
    p = DATA / name
    if not p.exists():
        return []
    with p.open() as fh:
        return list(csv.DictReader(fh))


def F(x):
    try:
        return float(x)
    except Exception:
        return float("nan")


def f3(x): return "--" if math.isnan(F(x)) else f"{F(x):.3f}"
def f4(x): return "--" if math.isnan(F(x)) else f"{F(x):.4f}"
def s4(x): return "--" if math.isnan(F(x)) else f"${F(x):+.4f}$"
def f2(x): return "--" if math.isnan(F(x)) else f"{F(x):.2f}"
def pc(x, nd=1): return "--" if math.isnan(F(x)) else f"{100 * F(x):.{nd}f}"
def ci(lo, hi, nd=4): return f"$[{F(lo):+.{nd}f}, {F(hi):+.{nd}f}]$"
def wlt(r, w="pos", l="neg", t="zero"): return f"{int(F(r[w]))}\\,/\\,{int(F(r[l]))}\\,/\\,{int(F(r[t]))}"
def pv(p):
    p = F(p)
    if math.isnan(p): return "--"
    if p >= 0.01: return f"{p:.2f}"
    e = int(math.floor(math.log10(p))); m = p / 10 ** e
    if round(m) >= 10: m, e = 1, e + 1
    return f"${m:.0f} \\times 10^{{{e}}}$"
def tex(s): return str(s).replace("_", "\\_").replace("&", "\\&").replace("%", "\\%")


WIDE = {"T2_related.tex", "T3_models.tex", "T7_labelfree.tex", "T8_options.tex", "A_conference.tex", "B_dk10.tex", "D_mde.tex", "E_certificate.tex", "F_interventions.tex", "T4_main.tex", "B_d29.tex", "T5_levels.tex", "G_synthetic.tex"}


def write(name, body):
    if name in WIDE:
        body = body.replace("\\begin{tabular}", "\\resizebox{\\linewidth}{!}{\\begin{tabular}", 1).replace("\\end{tabular}", "\\end{tabular}}", 1)
    (TAB / name).write_text("% GENERATED by reproduce/tables.py -- do not edit; every cell comes from data/\n" + body)


def by_family(rs, key="family"):
    d = OrderedDict((f, []) for f in FAMORDER)
    for r in rs:
        d.setdefault(r[key], []).append(r)
    return d


